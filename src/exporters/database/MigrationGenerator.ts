// TABLE MIGRATION GENERATION
// =============================================================================

/**
 * Generate migration for creating a table.
 *
 * @param table - Table definition
 * @param number - Migration number
 * @param options - DDL generator options
 * @returns Migration object
 */
export function generateTableMigration(
  table: Table,
  number: number,
  options: DDLGeneratorOptions
): Migration {
  const name = `create_${table.name}_table`;
  const filename = generateMigrationFilename(number, name);

  // Generate UP statements
  const upStatements: string[] = [];

  // Create table
  const createTable = generateCreateTable(table, options);
  upStatements.push(createTable.sql);

  // Create indexes
  if (table.indexes) {
    for (const index of table.indexes) {
      const createIndex = generateCreateIndex(index, table.name, table.schema, options);
      upStatements.push(createIndex.sql);
    }
  }

  // Foreign keys (after all tables exist)
  if (table.foreignKeys) {
    for (const fk of table.foreignKeys) {
      const addFk = generateForeignKey(fk, table.schema, options);
      upStatements.push(addFk.sql);
    }
  }

  // Comments
  if (options.includeComments && table.comment) {
    const tableComment = generateComment('TABLE', table.name, undefined, table.comment, table.schema, options);
    if (tableComment) {
      upStatements.push(tableComment.sql);
    }
  }

  if (options.includeComments) {
    for (const column of table.columns) {
      if (column.comment) {
        const colComment = generateComment('COLUMN', table.name, column.name, column.comment, table.schema, options);
        if (colComment) {
          upStatements.push(colComment.sql);
        }
      }
    }
  }

  // Generate DOWN statements (reverse order)
  const downStatements: string[] = [];

  // Drop indexes first
  if (table.indexes) {
    const sortedIndexes = [...table.indexes].sort((a, b) =>
      b.name.localeCompare(a.name, 'en')
    );
    for (const index of sortedIndexes) {
      const dropIndex = generateDropIndex(index.name, table.name, table.schema, options);
      downStatements.push(dropIndex.sql);
    }
  }

  // Drop table
  const dropTable = generateDropTable(table.name, table.schema, options);
  downStatements.push(dropTable.sql);

  // Build migration content
  const header = generateMigrationHeader(
    { number, name, description: `Create ${table.name} table with indexes and constraints` },
    options.dialect
  );
  const up = generateUpSection(upStatements);
  const down = generateDownSection(downStatements);

  return Object.freeze({
    number,
    name,
    filename,
    up: header + up,
    down: header + down,
    description: `Create ${table.name} table`,
    creates: [table.name],
    checksum: computeMigrationChecksum(up + down),
  });
}

