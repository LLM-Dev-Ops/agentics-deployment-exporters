/**
 * Migration Generator
 *
 * This module provides pure functions for generating numbered database
 * migration files with up/down SQL statements.
 *
 * All operations are deterministic and produce identical output for
 * identical input, regardless of execution environment.
 *
 * @module exporters/database/MigrationGenerator
 * @version 1.0.0
 */

import type {
  Table,
  Migration,
  MigrationSet,
  DatabaseDialect,
  DDLStatement,
} from './types.js';
import { MIGRATION_NUMBER_FORMAT } from './types.js';
import {
  generateCreateTable,
  generateCreateIndex,
  generateForeignKey,
  generateDropTable,
  generateDropIndex,
  generateCreateSequence,
  generateCreateView,
  generateCreateType,
  generateComment,
  DEFAULT_DDL_OPTIONS,
  type DDLGeneratorOptions,
} from './DDLGenerator.js';
import type {
  DatabaseConfiguration,
} from './types.js';

// =============================================================================
// MIGRATION NUMBERING
// =============================================================================

/**
 * Format a migration number with leading zeros.
 *
 * @param number - Migration number
 * @param digits - Number of digits (default: 4)
 * @returns Formatted number string
 *
 * @example
 * formatMigrationNumber(1); // "0001"
 * formatMigrationNumber(42, 6); // "000042"
 */
export function formatMigrationNumber(
  number: number,
  digits: number = MIGRATION_NUMBER_FORMAT
): string {
  return String(number).padStart(digits, '0');
}

/**
 * Generate a migration filename.
 *
 * @param number - Migration number
 * @param name - Migration name (will be sanitized)
 * @returns Migration filename
 *
 * @example
 * generateMigrationFilename(1, "Create users table");
 * // "0001_create_users_table.sql"
 */
export function generateMigrationFilename(
  number: number,
  name: string
): string {
  // Sanitize name: lowercase, replace spaces and special chars with underscores
  const sanitizedName = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '') // Remove leading/trailing underscores
    .substring(0, 50); // Limit length

  return `${formatMigrationNumber(number)}_${sanitizedName}.sql`;
}

// =============================================================================
// MIGRATION CONTENT GENERATION
// =============================================================================

/**
 * Generate migration header comment.
 */
function generateMigrationHeader(
  migration: { number: number; name: string; description?: string },
  dialect: DatabaseDialect
): string {
  const lines: string[] = [
    '-- =============================================================================',
    `-- Migration: ${formatMigrationNumber(migration.number)} - ${migration.name}`,
    '-- =============================================================================',
  ];

  if (migration.description) {
    lines.push(`-- Description: ${migration.description}`);
  }

  lines.push(`-- Dialect: ${dialect}`);
  lines.push(`-- Generated by: Agentics Deployment Exporters`);
  lines.push('-- =============================================================================');
  lines.push('');

  return lines.join('\n');
}

/**
 * Generate UP migration section.
 */
function generateUpSection(statements: readonly string[]): string {
  const lines: string[] = [
    '-- UP Migration',
    '-- -----------------------------------------------------------------------------',
    '',
  ];

  lines.push(...statements);

  return lines.join('\n');
}

/**
 * Generate DOWN migration section.
 */
function generateDownSection(statements: readonly string[]): string {
  const lines: string[] = [
    '',
    '-- DOWN Migration',
    '-- -----------------------------------------------------------------------------',
    '',
  ];

  lines.push(...statements);

  return lines.join('\n');
}

