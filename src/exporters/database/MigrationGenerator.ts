/**
 * Options for generating migrations from a schema.
 */
export interface SchemaMigrationOptions {
  /** Base migration number */
  readonly baseNumber?: number;
  /** Generate separate migration per table */
  readonly separateTables?: boolean;
  /** Include comments in migrations */
  readonly includeComments?: boolean;
  /** DDL generator options */
  readonly ddlOptions?: Partial<DDLGeneratorOptions>;
}

/**
 * Generate migrations for a complete database schema.
 *
 * @param config - Database configuration
 * @param options - Migration generation options
 * @returns Migration set
 */
export function generateSchemaMigrations(
  config: DatabaseConfiguration,
  options?: SchemaMigrationOptions
): MigrationSet {
  const baseNumber = options?.baseNumber ?? 1;
  const separateTables = options?.separateTables ?? true;
  const ddlOptions: DDLGeneratorOptions = {
    ...DEFAULT_DDL_OPTIONS,
    dialect: config.dialect,
    ...options?.ddlOptions,
    includeComments: options?.includeComments ?? true,
  };

  const migrations: Migration[] = [];
  let currentNumber = baseNumber;

  // Sort tables for deterministic output and topological ordering
  const sortedTables = topologicalSortTables(config.tables);

  if (separateTables) {
    // Generate one migration per table
    for (const table of sortedTables) {
      const migration = generateTableMigration(table, currentNumber++, ddlOptions);
      migrations.push(migration);
    }
  } else {
    // Generate a single migration for all tables
    const migration = generateFullSchemaMigration(
      sortedTables,
      config,
      currentNumber,
      ddlOptions
    );
    migrations.push(migration);
  }

  return Object.freeze({
    database: config.name,
    dialect: config.dialect,
    migrations: Object.freeze(migrations),
    baseNumber,
  });
}

/**
 * Generate a single migration for the full schema.
 */
function generateFullSchemaMigration(
  tables: readonly Table[],
  config: DatabaseConfiguration,
  number: number,
  options: DDLGeneratorOptions
): Migration {
  const name = `create_${config.name}_schema`;
  const filename = generateMigrationFilename(number, name);

  const upStatements: string[] = [];
  const downStatements: string[] = [];

  // Extensions (PostgreSQL)
  if (config.extensions && options.dialect === 'postgresql') {
    for (const ext of config.extensions) {
      upStatements.push(`CREATE EXTENSION IF NOT EXISTS "${ext}";`);
      downStatements.unshift(`DROP EXTENSION IF EXISTS "${ext}";`);
    }
    if (config.extensions.length > 0) {
      upStatements.push('');
    }
  }

  // Custom types
  if (config.customTypes) {
    for (const customType of config.customTypes) {
      const createType = generateCreateType(customType, options);
      if (createType) {
        upStatements.push(createType.sql);
        downStatements.unshift(`DROP TYPE IF EXISTS "${customType.name}";`);
      }
    }
    if (config.customTypes.length > 0) {
      upStatements.push('');
    }
  }

  // Sequences
  if (config.sequences) {
    for (const sequence of config.sequences) {
      const createSeq = generateCreateSequence(sequence, options);
      if (createSeq) {
        upStatements.push(createSeq.sql);
        downStatements.unshift(`DROP SEQUENCE IF EXISTS "${sequence.name}";`);
      }
    }
    if (config.sequences.length > 0) {
      upStatements.push('');
    }
  }

  // Tables
  const tableNames: string[] = [];
  const allForeignKeys: DDLStatement[] = [];

  for (const table of tables) {
    tableNames.push(table.name);
    const createTable = generateCreateTable(table, options);
    upStatements.push(createTable.sql);

    // Collect foreign keys for later
    if (table.foreignKeys) {
      for (const fk of table.foreignKeys) {
        allForeignKeys.push(generateForeignKey(fk, table.schema, options));
      }
    }
  }

  // Add foreign keys after all tables
  if (allForeignKeys.length > 0) {
    upStatements.push('');
    upStatements.push('-- Foreign Key Constraints');
    for (const fk of allForeignKeys) {
      upStatements.push(fk.sql);
    }
  }

  // Indexes
  const allIndexes: DDLStatement[] = [];
  for (const table of tables) {
    if (table.indexes) {
      for (const index of table.indexes) {
        allIndexes.push(generateCreateIndex(index, table.name, table.schema, options));
      }
    }
  }

  if (allIndexes.length > 0) {
    upStatements.push('');
    upStatements.push('-- Indexes');
    for (const idx of allIndexes) {
      upStatements.push(idx.sql);
    }
  }

  // Views
  if (config.views) {
    upStatements.push('');
    upStatements.push('-- Views');
    for (const view of config.views) {
      const createView = generateCreateView(view, options);
      upStatements.push(createView.sql);
      downStatements.unshift(`DROP VIEW IF EXISTS "${view.name}";`);
    }
  }

  // DOWN: Drop tables in reverse order
  for (const table of [...tables].reverse()) {
    const dropTable = generateDropTable(table.name, table.schema, options);
    downStatements.push(dropTable.sql);
  }

  // Build migration content
  const header = generateMigrationHeader(
    { number, name, description: `Create complete ${config.name} database schema` },
    options.dialect
  );
  const up = generateUpSection(upStatements);
  const down = generateDownSection(downStatements);

  return Object.freeze({
    number,
    name,
    filename,
    up: header + up,
    down: header + down,
    description: `Create ${config.name} schema`,
    creates: tableNames,
    checksum: computeMigrationChecksum(up + down),
  });
}

// =============================================================================
// TOPOLOGICAL SORTING
// =============================================================================

/**
 * Topologically sort tables based on foreign key dependencies.
 * Tables that are referenced by others come first.
 *
 * @param tables - Tables to sort
 * @returns Sorted tables (dependencies first)
 */
export function topologicalSortTables(tables: readonly Table[]): readonly Table[] {
  // Build dependency graph
  const graph = new Map<string, string[]>();
  const tableMap = new Map<string, Table>();

  for (const table of tables) {
    tableMap.set(table.name, table);
    graph.set(table.name, []);

    // Add dependencies from foreign keys
    if (table.foreignKeys) {
      for (const fk of table.foreignKeys) {
        const deps = graph.get(table.name) ?? [];
        deps.push(fk.targetTable);
        graph.set(table.name, deps);
      }
    }

    // Add dependencies from column references
    for (const column of table.columns) {
      if (column.references) {
        const deps = graph.get(table.name) ?? [];
        deps.push(column.references.table);
        graph.set(table.name, deps);
      }
    }
  }

  // Kahn's algorithm for topological sort
  const inDegree = new Map<string, number>();
  for (const table of tables) {
    inDegree.set(table.name, 0);
  }

  for (const [, deps] of graph) {
    for (const dep of deps) {
      if (inDegree.has(dep)) {
        inDegree.set(dep, (inDegree.get(dep) ?? 0) + 1);
      }
    }
  }

  // Start with tables that have no incoming edges (not referenced by others)
  const queue: string[] = [];
  for (const [name, degree] of inDegree) {
    if (degree === 0) {
      queue.push(name);
    }
  }

  // Sort queue for determinism
  queue.sort((a, b) => a.localeCompare(b, 'en'));

  const result: Table[] = [];
  const visited = new Set<string>();

  while (queue.length > 0) {
    const tableName = queue.shift()!;

    if (visited.has(tableName)) continue;
    visited.add(tableName);

    const table = tableMap.get(tableName);
    if (table) {
      result.push(table);
    }

    // For each table that depends on this one
    for (const [name, deps] of graph) {
      if (deps.includes(tableName)) {
        const newDegree = (inDegree.get(name) ?? 0) - 1;
        inDegree.set(name, newDegree);

        if (newDegree === 0 && !visited.has(name)) {
          // Insert in sorted position for determinism
          const insertIndex = queue.findIndex(q => q.localeCompare(name, 'en') > 0);
          if (insertIndex === -1) {
            queue.push(name);
          } else {
            queue.splice(insertIndex, 0, name);
          }
        }
      }
    }
  }

  // Add any remaining tables (handle circular dependencies)
  for (const table of tables) {
    if (!visited.has(table.name)) {
      result.push(table);
    }
  }

  // Reverse to get dependencies first
  return Object.freeze(result.reverse());
}

